/**
 * Robust CSV parser supporting quotes, multiline fields, and escaped quotes.
 */
export function parseCSV(csvText: string): Resident[] {
  const cleanText = csvText.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const rows: string[][] = [];
  let currentRow: string[] = [];
  let currentField = '';
  let insideQuotes = false;

  for (let i = 0; i < cleanText.length; i++) {
    const char = cleanText[i];
    const nextChar = cleanText[i + 1];

    if (insideQuotes) {
      if (char === '"' && nextChar === '"') {
        currentField += '"';
        i++; // skip next quote
      } else if (char === '"') {
        insideQuotes = false;
      } else {
        currentField += char;
      }
    } else {
      if (char === '"') {
        insideQuotes = true;
      } else if (char === ',') {
        currentRow.push(currentField.trim());
        currentField = '';
      } else if (char === '\n') {
        currentRow.push(currentField.trim());
        if (currentRow.some((f) => f.length > 0)) {
          rows.push(currentRow);
        }
        currentRow = [];
        currentField = '';
      } else {
        currentField += char;
      }
    }
  }

  // Last field/row
  if (currentField.length > 0 || currentRow.length > 0) {
    currentRow.push(currentField.trim());
    if (currentRow.some((f) => f.length > 0)) {
      rows.push(currentRow);
    }
  }

  if (rows.length === 0) return [];

  // Skip header if first row has "序號" or "學號"
  const header = rows[0];
  const hasHeader = header.some((cell) => cell.includes('序號') || cell.includes('學號') || cell.includes('姓名'));
  const dataRows = hasHeader ? rows.slice(1) : rows;

  return dataRows.map((row, index) => {
    const seq = row[0] || `${index + 1}`;
    const identity = row[1] || '';
    const name = row[2] || '';
    const studentId = row[3] || '';
    const dormitory = row[4] || '';
    const bed = row[5] || '';
    const flightArrival = row[6] || '';
    const vehicle = row[7] || '';
    const beddingRaw = row[8] || '0';
    const bedding = parseInt(beddingRaw.replace(/[^0-9]/g, ''), 10) || 0;

    // Normalize vehicle: converts fullwidth Ｈ/Ｊ/Ｉ to H/J/I
    let vehicleNormalized = vehicle.trim();
    vehicleNormalized = vehicleNormalized
      .replace(/Ｈ/g, 'H')
      .replace(/Ｊ/g, 'J')
      .replace(/Ｉ/g, 'I')
      .replace(/Ｂ/g, 'B')
      .replace(/Ｃ/g, 'C')
      .replace(/Ｄ/g, 'D')
      .replace(/Ｅ/g, 'E')
      .replace(/Ｆ/g, 'F')
      .replace(/Ｇ/g, 'G');

    // Categorize date
    let dateCategory = '未註明';
    if (flightArrival.includes('10/12')) {
      dateCategory = '10/12';
    } else if (flightArrival.includes('10/13')) {
      dateCategory = '10/13';
    } else if (flightArrival.includes('10/14')) {
      dateCategory = '10/14';
    } else if (flightArrival.includes('10/22')) {
      dateCategory = '10/22';
    } else if (flightArrival.includes('簽證') || flightArrival.includes('面試')) {
      dateCategory = '簽證辦理';
    }

    // Parse Room and Bed
    let roomNumber = '';
    let bedNumber = '';
    let roomAndBedDisplay = '';

    const cleanBed = bed.trim();
    const isUnassigned = !cleanBed || cleanBed.includes('#REF!') || cleanBed.includes('#N/A');

    if (isUnassigned) {
      roomNumber = '未分配';
      bedNumber = '待編排';
      roomAndBedDisplay = cleanBed.includes('#N/A') ? '待編排 (#N/A)' : '待編排 (#REF!)';
    } else if (cleanBed.includes('-')) {
      const parts = cleanBed.split('-');
      roomNumber = parts[0].trim();
      bedNumber = parts[1].trim();
      roomAndBedDisplay = `${roomNumber} 房 (${bedNumber}號床)`;
    } else {
      roomNumber = cleanBed;
      bedNumber = '1';
      roomAndBedDisplay = `${roomNumber} 房`;
    }

    return {
      id: `${index + 1}-${studentId || name}`,
      seq,
      identity,
      name,
      studentId,
      dormitory,
      bed: cleanBed,
      roomNumber,
      bedNumber,
      roomAndBedDisplay,
      flightArrival,
      vehicle,
      bedding,
      dateCategory,
      vehicleNormalized,
    };
  });
}

